// Regenerates wiki/Index.md from the kb_documents cache so agents can read one catalog, then only the pages they need.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { getDatabase, DEFAULT_DB_PATH } from '../modules/cache/db-schema.mjs';

const RESERVED = new Set(['Index.md', 'Home.md', 'Log.md', '_Sidebar.md']);
const SUB_INDEX = /^index-[a-z0-9-]+\.md$/;
const SUMMARY_MAX = 140;

function summarize(abstract, content) {
  let text = (abstract || '').trim();
  if (!text) {
    const lines = (content || '').split('\n');
    let i = 0;
    if (lines[0]?.trim() === '---') {
      i = lines.findIndex((l, n) => n > 0 && l.trim() === '---') + 1;
    }
    text = lines.slice(i).map((l) => l.trim()).find((l) => l && !l.startsWith('#')) || '';
  }
  text = text.replace(/\s+/g, ' ').replace(/\|/g, '/');
  return text.length > SUMMARY_MAX ? `${text.slice(0, SUMMARY_MAX - 1)}…` : text;
}

function slug(category) {
  return category.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'uncategorized';
}

export function generateWikiIndex({ dbPath = DEFAULT_DB_PATH, wikiDir = path.resolve('wiki'), prefix = 'wiki/', maxLines = 500 } = {}) {
  const db = getDatabase(dbPath, { readonly: true });
  let rows;
  try {
    rows = db.prepare('SELECT category, file_path, abstract, content FROM kb_documents WHERE file_path LIKE ? ORDER BY file_path').all(`${prefix}%`);
  } finally {
    db.close();
  }

  const groups = new Map();
  for (const row of rows) {
    const rel = row.file_path.slice(prefix.length);
    if (!rel.endsWith('.md') || RESERVED.has(rel) || SUB_INDEX.test(rel)) continue;
    const category = row.category || 'uncategorized';
    if (!groups.has(category)) groups.set(category, []);
    const summary = summarize(row.abstract, row.content);
    groups.get(category).push(`- [[${rel.slice(0, -3)}]]${summary ? ` — ${summary}` : ''}`);
  }
  const categories = [...groups.keys()].sort();
  const pages = categories.reduce((n, c) => n + groups.get(c).length, 0);
  const header = ['# Index', '', `<!-- Generated by scripts/generate-wiki-index.mjs from kb_documents. Do not edit. -->`, '', `${pages} pages.`, ''];

  const files = {};
  const flat = [...header];
  for (const c of categories) flat.push(`## ${c}`, '', ...groups.get(c), '');
  if (flat.length <= maxLines) {
    files['Index.md'] = flat;
  } else {
    const top = [...header];
    for (const c of categories) {
      const name = `index-${slug(c)}`;
      top.push(`- [[${name}]] — ${c} (${groups.get(c).length} pages)`);
      files[`${name}.md`] = [`# Index: ${c}`, '', `<!-- Generated by scripts/generate-wiki-index.mjs. Do not edit. -->`, '', ...groups.get(c), ''];
    }
    top.push('');
    files['Index.md'] = top;
  }

  fs.mkdirSync(wikiDir, { recursive: true });
  for (const f of fs.readdirSync(wikiDir)) {
    if (SUB_INDEX.test(f) && !(f in files)) fs.unlinkSync(path.join(wikiDir, f));
  }
  for (const [name, lines] of Object.entries(files)) fs.writeFileSync(path.join(wikiDir, name), lines.join('\n'));

  return { pages, lines: files['Index.md'].length, files: Object.keys(files).sort() };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
  const result = generateWikiIndex({
    dbPath: arg('db') ? path.resolve(arg('db')) : DEFAULT_DB_PATH,
    wikiDir: path.resolve(arg('wiki') || 'wiki'),
  });
  console.log(`[wiki-index] ${result.pages} pages, Index.md ${result.lines} lines, ${result.files.length} file(s)`);
}
