// 2. L35: Read-Only Check test
test('L35: Read-Only Check test', () => {
  // Ensure workspace is healthy first
  execSync('npm run kb:dag', { cwd: rootDir, encoding: 'utf8' });

  const getSnapshot = () => {
    const files = [];
    const walk = (d) => {
      for (const item of fs.readdirSync(d)) {
        const full = path.join(d, item);
        const stat = fs.statSync(full);
        if (stat.isDirectory()) walk(full);
        else files.push({ path: full, mtimeMs: stat.mtimeMs, size: stat.size });
      }
    };
    if (fs.existsSync(nlmDir)) walk(nlmDir);
    if (fs.existsSync(docsFile)) {
      const s = fs.statSync(docsFile);
      files.push({ path: docsFile, mtimeMs: s.mtimeMs, size: s.size });
    }
    return files;
  };

  const snapBefore = getSnapshot();
  const output = execSync('npm run kb:dag:check', { cwd: rootDir, encoding: 'utf8' });
  assert.ok(output.includes('[OK] KBSync DAG Health Check PASS'), 'Check output should indicate PASS');
  const snapAfter = getSnapshot();

  assert.equal(snapBefore.length, snapAfter.length, 'File count should not change');
  for (let i = 0; i < snapBefore.length; i++) {
    assert.equal(snapBefore[i].path, snapAfter[i].path);
    assert.equal(snapBefore[i].mtimeMs, snapAfter[i].mtimeMs, `File ${snapBefore[i].path} should not be modified`);
    assert.equal(snapBefore[i].size, snapAfter[i].size);
  }
});

// 3. L58: JSON Schema Validation test
test('L58: JSON Schema Validation test', () => {
  execSync('npm run kb:dag', { cwd: rootDir, encoding: 'utf8' });
  const ptr = JSON.parse(fs.readFileSync(pointerFile, 'utf8'));
  const genDir = path.join(gensDir, ptr.active_generation);

  const dagSchema = JSON.parse(fs.readFileSync(path.join(rootDir, 'kb-sync', 'schemas', 'dag.schema.v2.json'), 'utf8'));
  const adjSchema = JSON.parse(fs.readFileSync(path.join(rootDir, 'kb-sync', 'schemas', 'adjacency.schema.v2.json'), 'utf8'));

  const dag = JSON.parse(fs.readFileSync(path.join(genDir, 'dag.json'), 'utf8'));
  const adj = JSON.parse(fs.readFileSync(path.join(genDir, 'adjacency.json'), 'utf8'));

  // Validate DAG against Schema rules
  assert.equal(dag.$schema, dagSchema.properties.$schema ? dag.$schema : 'https://json-schema.org/draft/2020-12/schema');
  assert.equal(dag.version, dagSchema.properties.version.const);
  assert.ok(dag.metadata, 'DAG metadata must exist');
  assert.ok(/^sha256:[a-f0-9]{64}$/.test(dag.metadata.content_hash), 'content_hash must match sha256 pattern');
  assert.ok(typeof dag.metadata.created_at === 'string');
  assert.ok(Number.isInteger(dag.metadata.source_file_count) && dag.metadata.source_file_count >= 0);
  assert.ok(Number.isInteger(dag.metadata.total_nodes) && dag.metadata.total_nodes >= 0);
  assert.ok(Number.isInteger(dag.metadata.total_edges) && dag.metadata.total_edges >= 0);
  assert.ok(Number.isInteger(dag.metadata.cycles_count) && dag.metadata.cycles_count >= 0);
  assert.ok(typeof dag.metadata.generation_id === 'string');

  const validNodeTypes = ['file', 'chunk', 'dangling'];
  const validNodeStatuses = ['valid', 'missing', 'stale'];
  const validTargetKinds = ['file', 'chunk', 'external'];

  const nodeIds = new Set();
  for (const node of dag.nodes) {
    assert.ok(node.id && typeof node.id === 'string');
    assert.ok(!nodeIds.has(node.id), `Node ID ${node.id} must be unique`);
    nodeIds.add(node.id);
    assert.ok(validNodeTypes.includes(node.node_type), `Invalid node_type: ${node.node_type}`);
    assert.ok(typeof node.label === 'string');
    assert.ok(typeof node.path === 'string');
    assert.ok(validNodeStatuses.includes(node.status), `Invalid status: ${node.status}`);
    assert.ok(validTargetKinds.includes(node.target_kind), `Invalid target_kind: ${node.target_kind}`);
    assert.ok(Array.isArray(node.tags));
  }

  const validRelations = ['contains', 'wikilink', 'mdlink', 'mention'];
  const edgeIds = new Set();
  for (const edge of dag.edges) {
    assert.ok(edge.id && typeof edge.id === 'string');
    assert.ok(!edgeIds.has(edge.id), `Edge ID ${edge.id} must be unique`);
    edgeIds.add(edge.id);
    assert.ok(typeof edge.source === 'string');
    assert.ok(typeof edge.target === 'string');
    assert.ok(validRelations.includes(edge.relation), `Invalid relation: ${edge.relation}`);
  }

  // Validate Adjacency against Schema rules & 100% coverage
  assert.equal(adj.version, adjSchema.properties.version.const);
  assert.ok(adj.forward && typeof adj.forward === 'object');
  assert.ok(adj.reverse && typeof adj.reverse === 'object');

  for (const nid of nodeIds) {
    assert.ok(Object.prototype.hasOwnProperty.call(adj.forward, nid), `Adjacency forward map missing key for node: ${nid}`);
    assert.ok(Object.prototype.hasOwnProperty.call(adj.reverse, nid), `Adjacency reverse map missing key for node: ${nid}`);
    assert.ok(Array.isArray(adj.forward[nid]));
    assert.ok(Array.isArray(adj.reverse[nid]));
  }
});

