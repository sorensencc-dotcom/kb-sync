// 7. L135: GC Retention with Stale Active Pointer test
test('L135: GC Retention with Stale Active Pointer test', () => {
  // Clear existing mock generations for clean test isolation
  if (fs.existsSync(gensDir)) {
    for (const d of fs.readdirSync(gensDir)) {
      fs.rmSync(path.join(gensDir, d), { recursive: true, force: true });
    }
  }

  // Create 5 valid generations sorted by timestamp (Gen5 newest, Gen1 oldest)
  const g1 = '20260808_010000_00000001';
  const g2 = '20260808_020000_00000002';
  const g3 = '20260808_030000_00000003';
  const g4 = '20260808_040000_00000004';
  const g5 = '20260808_050000_00000005';

  createMockGen(g1);
  createMockGen(g2);
  createMockGen(g3);
  createMockGen(g4);
  createMockGen(g5);

  // Set active pointer to g1 (ranked 5th by recency, stale active pointer)
  fs.writeFileSync(pointerFile, JSON.stringify({ active_generation: g1, sha256: 'sha256:0000' }, null, 2));

  // Run Garbage Collection
  runGC();

  // Assert retained generations in gensDir:
  // Must retain 4 total: active (g1) + 3 top recent valid (g5, g4, g3)
  // Purged: g2
  const remaining = fs.readdirSync(gensDir).sort();
  assert.equal(remaining.length, 4, 'GC must retain exactly 4 generations');
  assert.deepEqual(remaining, [g1, g3, g4, g5], 'GC must retain active (g1) and top 3 recent valid (g5, g4, g3), purging g2');
});

