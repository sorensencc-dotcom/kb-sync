// 5. L92: Self-Healing Forward Mismatch test
test('L92: Self-Healing Forward Mismatch test', () => {
  // Create Gen 1 and make it active
  const gen1 = '20260808_100000_11111111';
  const mock1 = createMockGen(gen1);
  fs.writeFileSync(pointerFile, JSON.stringify({ active_generation: gen1, sha256: 'sha256:1111' }, null, 2));
  fs.writeFileSync(docsFile, mock1.docText);

  // Create Gen 2 (newest)
  const gen2 = '20260808_110000_22222222';
  const mock2 = createMockGen(gen2);

  // Simulate crash between Step 2 (doc rename to Gen 2) and Step 3 (pointer swap):
  // docs/KB_SYNC_DAG.md has Gen 2 content, but pointer still points to Gen 1
  fs.writeFileSync(docsFile, mock2.docText);

  // Health check should flag mismatch between docs/KB_SYNC_DAG.md and Gen 1's doc
  const healthBefore = checkHealth();
  assert.equal(healthBefore.healthy, false, 'Health check must flag doc-vs-pointer mismatch');

  // Run recovery scan
  const recovered = runRecovery();
  assert.ok(recovered, 'Recovery should succeed');

  // Assert recovery adopted newest valid generation (Gen 2)
  const ptrAfter = JSON.parse(fs.readFileSync(pointerFile, 'utf8'));
  assert.equal(ptrAfter.active_generation, gen2, 'Recovery should adopt newest valid generation (Gen 2)');
  assert.equal(fs.readFileSync(docsFile, 'utf8'), mock2.docText, 'docs/KB_SYNC_DAG.md should be updated to Gen 2 doc');

  // Health check should now pass
  const healthAfter = checkHealth();
  assert.ok(healthAfter.healthy, 'Health check must pass after recovery');
});

